################################################################################################################################################################################
# Script to setup a load test scenario subfolder for a Power BI report.
#
# v1.0 Stage 1 changes:
#   - PBIToken.json plumbing REMOVED (auth is MSAL only — see auth-config.json).
#   - UpdateTokenFile / Get-PowerBIAccessToken calls REMOVED.
#   - Banner clarifies that this script will be fully replaced by Setup.html in v1.0 Stage 5.
#
# What this still does:
#   - Prompts for workspace + report via the MicrosoftPowerBIMgmt module.
#   - Creates a new subfolder per chosen report named "<workspace> - <report> - <timestamp>".
#   - Copies RealisticLoadTest.html, then writes a PBIReport.JSON in the subfolder with the
#     selected workspace/report/embed-URL and the answers to numberOfViews / thinkTime / projectName.
#   - Injects Filters.json / Bookmarks.json / Page.json templates from the tool root.
#
# Important caveat:
#   In v1.0 Stage 1 the runner (`node runner/run.js`) only reads the ROOT-level PBIReport.json,
#   not subfolder copies. Subfolders generated by this script are useful as scenario archives
#   but cannot yet be invoked end-to-end. Stage 4 brings back multi-scenario via loadtest.yaml,
#   and Stage 5 retires this script entirely in favor of Setup.html.
################################################################################################################################################################################

Write-Host "[v1.0 Stage 1] Setup_Load_Test.ps1 still works for single-scenario configuration." -ForegroundColor Yellow
Write-Host "                Token plumbing was removed — auth is MSAL only (auth-config.json)." -ForegroundColor Yellow
Write-Host "                This script will be replaced by Setup.html in v1.0 Stage 5." -ForegroundColor Yellow
Write-Host "" -ForegroundColor Yellow

#Variables declaration
$destinationDir = ''
$workingDir = $pwd.Path
$masterFilesExists = $true
$htmlFileName = 'RealisticLoadTest.html'
$filtersFileName = 'Filters.json'
$pageFileName = 'Page.json'
$bookmarksFileName = 'Bookmarks.json'
$reportConfig = @{}
$reports = @()
$user = @{}

# Regular expressions to match and update JSON files
$reportUrlRegex = '(?<=reportUrl\":\s*\").*?(?=\")'
$pageIDRegex = '\/\/"pageName".*"'
$bookmarksRegex = '\/\/"bookmarkList".*]'
$noViewsRegex = '"numberOfViews":\s*(\d+),'
$filtersRegex = '"filters".*]'
$thinkTimeRegex = '"thinkTimeSeconds":\s*(\d+)'
$projectNameRegex = '"projectName":.*"'


#Function implementation to update report parameters file
function UpdateReportParameters
{
    $reportJSONFile = Get-Content $(Join-Path $workingDir 'PBIReport.JSON') -raw;
    $new_ReportJSONFile = ($reportJSONFile -replace $reportUrlRegex,$args[0]);
    $new_ReportJSONFile = ($new_ReportJSONFile -replace $noViewsRegex,('"numberOfViews": ' + $args[1] + ','));
    $new_ReportJSONFile = ($new_ReportJSONFile -replace $thinkTimeRegex,('"thinkTimeSeconds": '+ $args[2]));
    $new_ReportJSONFile = ($new_ReportJSONFile -replace $projectNameRegex,('"projectName": "' + $args[3] + '"'));
    $filtersJSONFile = Get-Content $(Join-Path $workingDir $filtersFileName) -raw;
    $pageJSONFile = Get-Content $(Join-Path $workingDir $pageFileName) -raw;
    $bookmarksJSONFile = Get-Content $(Join-Path $workingDir $bookmarksFileName) -raw;
    $new_ReportJSONFile = ($new_ReportJSONFile -replace $filtersRegex, $filtersJSONFile);
    $new_ReportJSONFile = ($new_ReportJSONFile -replace $pageIDRegex, $pageJSONFile);
    $new_ReportJSONFile = ($new_ReportJSONFile -replace $bookmarksRegex, $bookmarksJSONFile);
    $new_ReportJSONFile
    $destinationDir
    $new_ReportJSONFile | set-content $(Join-Path $destinationDir 'PBIReport.JSON')
}

#verify if current working directory has the master files. If not, prompt user for path of the files.
while($masterFilesExists)
{
    if(!(Test-Path -path $(Join-Path $workingDir $htmlFileName)) -and !(Test-Path -path $(Join-Path $workingDir 'PBIReport.JSON')))
    {
        Write-Host "The current working directory ($workingDir) doesn't have the master files required to proceed further." -ForegroundColor Yellow
        $workingDir = Read-Host -Prompt "Enter the directory path having master files"
    }
    else
    {
        $masterFilesExists = $false
    }
}

[int]$reportCount = Read-Host "How many reports you want to configure?"
[int]$noViews = Read-Host "How many views you want to generate per report?"
[int]$thinkTime = Read-Host "How much think time between interaction? (sec)"
$projectName = Read-Host "What is the name of the project?"
$increment = 1
while($reportCount -gt 0)
{
    Write-Host "Gathering inputs for report $increment" -ForegroundColor Red

    # Get required inputs from user
    Write-Host "Select Id to authenticate to Power BI" -ForegroundColor Yellow
    $user = Login-PowerBI
    $user

    #Accessing list of workspaces
    $workSpaceList = Get-PowerBIWorkspace

    $workSpaceCounter = 1
    foreach($workSpace in $workSpaceList)
    {
        Write-Host "[$($workSpaceCounter)]" -ForegroundColor Yellow -NoNewline
        Write-Host " - $($workSpace.Id) - $($workSpace.Name)" -ForegroundColor Green
        ++$workSpaceCounter
    }

    $workSpaceSelection = Read-Host "Select Work space index from above"

    #Accessing reports from selected work space
    Write-Host "Listing all reports from the selected work space" -ForegroundColor Yellow
    $reportList = Get-PowerBIReport -WorkspaceId $($workSpaceList[$workSpaceSelection-1].Id)

    $reportCounter = 1
    foreach($report in $reportList)
    {
        Write-Host "[$($reportCounter)]" -ForegroundColor Yellow -NoNewline
        Write-Host " - $($report.Id) - $($report.Name)" -ForegroundColor Green
        ++$reportCounter
    }

    $reportSelection = Read-Host "Select report index from above"

    $reportUrl = $($reportList[$reportSelection-1].EmbedUrl)
    $reportName = $($reportList[$reportSelection-1].Name)
    $workspaceName = $($workspaceList[$workspaceSelection-1].Name)
    $reportList[$reportSelection-1]


    #Creating sub-folder to create a report set
    $currentDate = get-date -f MM-dd-yy_HHmmss
    $destinationDir = new-item -Path $workingDir -Name "$($workspaceName) - $($reportName) - $($currentDate)" -ItemType directory

    #Copy master html file into the new directory
    Copy-Item $(Join-Path $workingDir $htmlFileName) -Destination $destinationDir

    #Function call to update report parameters file
    UpdateReportParameters $reportUrl $noViews $thinkTime $projectName

    $reportConfig.WorkSpace = $($workSpaceList[$workSpaceSelection-1].Name)
    $reportConfig.ReportName = $($reportList[$reportSelection-1].Name)
    $reportConfig.ConfiguredReportPath = $(Join-Path $destinationDir $htmlFileName)

    $reports += New-Object PSobject -Property $reportConfig
    --$reportCount
    $increment++
}
Write-Host "Listing reports configuration" -ForegroundColor Yellow
$reports | Format-Table -AutoSize

"Subfolders are an archive of scenario configs. To run end-to-end in v1.0 Stage 1, copy the desired"
"PBIReport.JSON to the tool root and run:  cd runner; node run.js --concurrency N"
"(Multi-scenario invocation comes back in Stage 4 via loadtest.yaml.)"
